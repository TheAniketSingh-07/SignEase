'use client'

import React, { useState, useEffect } from 'react'
import { useParams, useRouter } from 'next/navigation'
import Link from 'next/link'
import Logo from '@/components/ui/Logo'
import { hybridStore } from '@/lib/supabase/hybridStore'
import {
  Download,
  Copy,
  Check,
  FileText,
  Sparkles,
  ArrowLeft,
  Calendar,
  Share2,
  CheckCircle2,
  Tag,
  BookOpen,
} from 'lucide-react'
import { useAccessibility } from '@/components/AccessibilityProvider'
import ClassroomNotFound from '@/components/ClassroomNotFound'

export default function LectureSummaryPage() {
  const params = useParams()
  const router = useRouter()
  const code = (params.code || 'NXJS428').toUpperCase()

  const [activeTab, setActiveTab] = useState('summary') // 'summary' or 'transcript'
  const [classroom, setClassroom] = useState(null)
  const [notFound, setNotFound] = useState(false)
  const [transcripts, setTranscripts] = useState([])
  const [summaryData, setSummaryData] = useState(null)
  const [loadingAI, setLoadingAI] = useState(false)
  const [copied, setCopied] = useState(false)

  const { getCaptionFontSizeClass } = useAccessibility()

  useEffect(() => {
    let isCancelled = false
    const loadData = async () => {
      try {
        const c = await hybridStore.getClassroomByCode(code)
        if (isCancelled) return
        if (!c) {
          setNotFound(true)
          return
        }
        setClassroom(c)

        const transcriptList = await hybridStore.getTranscripts(code)
        if (isCancelled) return
        const safeTrans = Array.isArray(transcriptList) ? transcriptList : []
        setTranscripts(safeTrans)

        handleGenerateSummary(safeTrans, c?.subject)
      } catch (err) {
        console.warn('Failed to load classroom summary:', err)
      }
    }
    loadData()
    return () => {
      isCancelled = true
    }
  }, [code])

  if (notFound) {
    return <ClassroomNotFound code={code} />
  }

  const handleGenerateSummary = async (transList = transcripts, subj = '') => {
    setLoadingAI(true)
    const transcriptText = transList.map((t) => `${t.speaker}: ${t.text}`).join('\n')

    try {
      const res = await fetch('/api/ai/summary', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          transcriptText,
          classroomTopic: subj || classroom?.subject || 'Next.js API Development',
        }),
      })
      const data = await res.json()
      if (data.summary) {
        setSummaryData(data.summary)
        hybridStore.saveSummary(code, data.summary)
      }
    } catch (err) {
      console.warn('Summary fetch error:', err)
    } finally {
      setLoadingAI(false)
    }
  }

  const handleDownloadSummary = () => {
    if (!summaryData) return
    const content = `# Lecture Summary: ${summaryData.topic}
Classroom Code: ${code}
Date: ${classroom?.scheduled_date || new Date().toLocaleDateString()}
Teacher: ${classroom?.teacher_name || 'Instructor'}

## Key Points
${(summaryData.key_points || []).map((p) => `- ${p}`).join('\n')}

## Important Terms
${(summaryData.important_terms || []).join(', ')}

## Summary
${summaryData.full_summary || ''}

## Action Items
${(summaryData.action_items || []).map((a) => `- ${a}`).join('\n')}

---
Generated by SignEase AI Classroom Assistant
`
    const blob = new Blob([content], { type: 'text/markdown;charset=utf-8' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = `Lecture-Summary-${code}.md`
    a.click()
    URL.revokeObjectURL(url)
  }

  const handleCopySummary = () => {
    if (!summaryData) return
    const content = `Lecture Summary: ${summaryData.topic}\n\nKey Points:\n${summaryData.key_points?.map((p) => `• ${p}`).join('\n')}`
    navigator.clipboard.writeText(content)
    setCopied(true)
    setTimeout(() => setCopied(false), 2000)
  }

  return (
    <div className="min-h-screen bg-slate-50 flex flex-col">
      {/* Top Header */}
      <header className="bg-white border-b border-slate-200/80 px-6 py-4 flex items-center justify-between">
        <div className="flex items-center gap-4">
          <Logo />
          <div className="h-6 w-px bg-slate-200 hidden sm:block" />
          <div>
            <h1 className="text-base sm:text-lg font-bold text-slate-900 leading-tight">
              {classroom?.name || 'Web Development'}
            </h1>
            <p className="text-xs text-slate-500">
              Code: <span className="font-mono font-bold text-brand-600">{code}</span>
            </p>
          </div>
        </div>

        <div className="flex items-center gap-3">
          <button
            onClick={() => {
              const u = hybridStore.getCurrentUser()
              if (u?.role === 'student') {
                router.push('/student/dashboard')
              } else {
                router.push('/teacher/dashboard')
              }
            }}
            className="inline-flex items-center gap-1.5 px-4 py-2 text-xs font-semibold text-slate-700 bg-slate-100 hover:bg-slate-200 rounded-xl transition"
          >
            <ArrowLeft className="w-3.5 h-3.5" />
            Back to Dashboard
          </button>
        </div>
      </header>

      {/* Main Container */}
      <main className="max-w-5xl w-full mx-auto p-6 sm:p-8 flex-1">
        {/* Navigation Tabs (Screen 9 in Mockup) */}
        <div className="flex items-center justify-between mb-6 border-b border-slate-200 pb-2">
          <div className="flex items-center gap-3">
            <button
              onClick={() => setActiveTab('transcript')}
              className={`px-5 py-2.5 rounded-xl text-sm font-semibold transition ${
                activeTab === 'transcript'
                  ? 'bg-brand-500 text-white shadow-sm'
                  : 'text-slate-600 hover:bg-slate-200/60'
              }`}
            >
              Transcript
            </button>
            <button
              onClick={() => setActiveTab('summary')}
              className={`px-5 py-2.5 rounded-xl text-sm font-semibold transition flex items-center gap-2 ${
                activeTab === 'summary'
                  ? 'bg-brand-500 text-white shadow-sm'
                  : 'text-slate-600 hover:bg-slate-200/60'
              }`}
            >
              <Sparkles className="w-4 h-4" />
              AI Summary
            </button>
          </div>

          <div className="flex items-center gap-2">
            {activeTab === 'summary' && (
              <button
                onClick={() => handleGenerateSummary()}
                disabled={loadingAI}
                className="inline-flex items-center gap-1.5 px-3 py-2 text-xs font-semibold text-brand-700 bg-brand-50 hover:bg-brand-100 rounded-xl border border-brand-200 transition"
              >
                <Sparkles className="w-3.5 h-3.5" />
                {loadingAI ? 'Summarizing...' : 'Regenerate AI'}
              </button>
            )}

            <button
              onClick={handleDownloadSummary}
              className="inline-flex items-center gap-1.5 px-4 py-2 text-xs font-bold text-white bg-brand-500 hover:bg-brand-600 rounded-xl shadow-xs transition"
            >
              <Download className="w-3.5 h-3.5" />
              Download
            </button>
          </div>
        </div>

        {/* TAB 1: AI SUMMARY (Screen 9 in Mockup) */}
        {activeTab === 'summary' && (
          <div className="bg-white rounded-2xl border border-slate-200/80 shadow-2xs p-8 sm:p-10 space-y-8">
            {/* Header with Title */}
            <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-6 border-b border-slate-100">
              <div>
                <h2 className="text-2xl font-extrabold text-slate-900 tracking-tight">
                  Lecture Summary
                </h2>
                <div className="mt-2 flex items-center gap-2 text-xs text-slate-500">
                  <span className="font-semibold text-slate-400 uppercase tracking-wider">
                    Topic:
                  </span>
                  <span className="font-bold text-slate-800 text-sm">
                    {summaryData?.topic || 'Next.js API Development'}
                  </span>
                </div>
              </div>

              <button
                onClick={handleCopySummary}
                className="self-start sm:self-auto inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium text-slate-600 bg-slate-50 hover:bg-slate-100 border border-slate-200 rounded-lg transition"
              >
                {copied ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5" />}
                {copied ? 'Copied' : 'Copy'}
              </button>
            </div>

            {/* Key Points Bullet List (Screen 9) */}
            <div className="space-y-4">
              <h3 className="text-base font-bold text-slate-900">Key Points</h3>
              <ul className="space-y-3">
                {summaryData?.key_points?.map((point, idx) => (
                  <li key={idx} className="flex items-start gap-3">
                    <span className="w-2 h-2 rounded-full bg-brand-500 mt-2 shrink-0" />
                    <p className="text-sm text-slate-700 leading-relaxed">{point}</p>
                  </li>
                ))}
              </ul>
            </div>

            {/* Important Terms Tags (Screen 9) */}
            <div className="space-y-3 pt-4 border-t border-slate-100">
              <h3 className="text-base font-bold text-slate-900">Important Terms</h3>
              <div className="flex flex-wrap gap-2.5">
                {summaryData?.important_terms?.map((term, idx) => (
                  <span
                    key={idx}
                    className="px-3.5 py-1.5 bg-brand-50 text-brand-700 font-semibold text-xs rounded-lg border border-brand-200/80 hover:bg-brand-100 transition cursor-default"
                  >
                    {term}
                  </span>
                ))}
              </div>
            </div>

            {/* Full Summary Paragraph */}
            {summaryData?.full_summary && (
              <div className="space-y-3 pt-4 border-t border-slate-100">
                <h3 className="text-base font-bold text-slate-900">Overview</h3>
                <p className="text-sm text-slate-600 leading-relaxed bg-slate-50/70 p-4 rounded-xl border border-slate-100">
                  {summaryData.full_summary}
                </p>
              </div>
            )}

            {/* Action Items */}
            {summaryData?.action_items && summaryData.action_items.length > 0 && (
              <div className="space-y-3 pt-4 border-t border-slate-100">
                <h3 className="text-base font-bold text-slate-900">Action Items for Students</h3>
                <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                  {summaryData.action_items.map((item, idx) => (
                    <div
                      key={idx}
                      className="p-3 bg-emerald-50/60 border border-emerald-100 rounded-xl flex items-start gap-2.5 text-xs text-emerald-800"
                    >
                      <CheckCircle2 className="w-4 h-4 text-emerald-600 shrink-0 mt-0.5" />
                      <span>{item}</span>
                    </div>
                  ))}
                </div>
              </div>
            )}
          </div>
        )}

        {/* TAB 2: FULL TRANSCRIPT */}
        {activeTab === 'transcript' && (
          <div className="bg-white rounded-2xl border border-slate-200/80 shadow-2xs p-8 space-y-4">
            <h2 className="text-xl font-bold text-slate-900">Full Lecture Transcript</h2>
            <div className="divide-y divide-slate-100">
              {transcripts.length === 0 ? (
                <p className="py-8 text-center text-sm text-slate-400">
                  No transcript entries recorded for this lecture.
                </p>
              ) : (
                transcripts.map((t, idx) => (
                  <div key={idx} className="py-3.5 flex items-start gap-4">
                    <span className="text-xs font-semibold text-slate-400 w-20 shrink-0 pt-0.5">
                      {t.timestamp || '10:00 AM'}
                    </span>
                    <div className="flex-1">
                      <p className="text-xs font-bold text-slate-800 mb-0.5">{t.speaker}</p>
                      <p className={`text-slate-700 ${getCaptionFontSizeClass()}`}>{t.text}</p>
                    </div>
                  </div>
                ))
              )}
            </div>
          </div>
        )}
      </main>
    </div>
  )
}
